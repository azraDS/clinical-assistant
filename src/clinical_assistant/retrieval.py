"""Retrieval over the filtered statement set: BM25 + dense hybrid search, cross-encoder rerank,
care-domain query reformulation (template + LLM), and LLM-based direct retrieval. The pipeline
default is llm_based_retrieval_plus_query_reformulation. See notebooks/README.md §4.
Ported from notebooks/02_retrieval_pipeline.ipynb §9-10, §12.
"""

import re
from collections import defaultdict

import numpy as np
from langfuse import observe
from pydantic import BaseModel, Field

from . import config
from .eligibility import label_statement_eligibility
from .knowledge_base import KnowledgeBase
from .patient import PatientState, derive

STOPWORDS = set(
    "a an the of in and or for to with by on at as is are be be that this these those from use using people person".split()
)


def tokenize(text: str) -> list[str]:
    return [t for t in re.findall(r"[a-z0-9]+(?:[-/][a-z0-9]+)*", text.lower()) if t not in STOPWORDS]


def index_text(s: dict) -> str:
    return f"{s['statement_id']} | {s['heading_path']}\n{s['text']}"


class SubQueries(BaseModel):
    queries: list[str] = Field(description="Short retrieval queries, each about one clinical question, phrased like guideline text")


class Screening(BaseModel):
    relevant: list[str] = Field(description="statement_ids relevant to this visit, most important first")


@observe(name="template_subqueries", as_type="span", capture_input=False)
def build_template_subqueries(st: PatientState) -> list[str]:
    """Code checklist, no LLM: one query per care domain the patient's own state triggers. See
    `build_llm_gap_subqueries` for the LLM-generated queries that cover what this checklist
    doesn't have a rule for.

    capture_input=False: without it @observe wraps the single positional arg as a generic
    {"args": [...], "kwargs": {}} — a clean, explicitly-labeled input reads better."""
    config.set_trace_input({"patient_state": st.model_dump()})
    d = derive(st)
    g = d["gfr_category"] or "unknown GFR category"
    pop = "adults" if d["is_adult"] else "children"
    q = []

    if st.egfr is not None and st.egfr < 60 and not st.known_ckd:
        q.append(f"confirm chronicity of CKD after a single low eGFR; repeat testing; evaluate cause of CKD in {pop}")
    q.append(f"test urine albumin-to-creatinine ratio ACR and eGFR to detect and stage CKD {g} in {pop}")
    if st.egfr is not None and st.egfr < 60:
        q += [
            f"frequency of monitoring eGFR and albuminuria in people with CKD {g}",
            f"kidney failure risk prediction equation and criteria for referral to nephrology in CKD {g}",
            f"statin treatment to reduce cardiovascular risk in {pop} aged {st.age} with eGFR {st.egfr:g}",
            f"SGLT2 inhibitor treatment for {pop} with CKD eGFR {st.egfr:g}",
            "renin-angiotensin system inhibitor ACEi or ARB for CKD with albuminuria",
            f"medication management, drug dosing and nephrotoxic drug avoidance with reduced eGFR {st.egfr:g}",
        ]
    if st.hypertension or (st.sbp and st.sbp >= 130):
        q.append(f"blood pressure target and antihypertensive treatment for {pop} with CKD and high blood pressure")
    if "RASi" in d["drug_classes"]:
        q.append("monitoring potassium and creatinine in people on ACEi or ARB; continue RASi when eGFR declines")
    if st.diabetes in ("type_1", "type_2"):
        q.append("glucose-lowering therapy SGLT2i GLP-1 receptor agonist and finerenone in CKD with type 2 diabetes")
    for symptom in st.symptoms:
        q.append(f"assessment and management of {symptom} and uremic symptoms in CKD")
    if st.potassium and st.potassium > 5.0:
        q.append("management of hyperkalemia in CKD")
    return q


LLM_GAP_SUBQUERIES_SYSTEM = (
    "You are given a fixed checklist of guideline look-up queries already generated by code for this patient. "
    "Read the patient's state, derived values and visit note, and find clinically important topics relevant to "
    "THIS visit that the checklist does not already cover — e.g. a specific symptom, medication, condition or "
    "concern mentioned in the note. Return ONLY new queries for those gaps, phrased like guideline text, one per "
    "topic. Do not repeat or rephrase anything already in the checklist. If the checklist already covers "
    "everything relevant, return an empty list."
)


def _call_llm_for_subqueries(st: PatientState, note: str, template_queries: list[str]):
    # langfuse.openai's client wrapper auto-traces this call (full prompt, output, token usage) —
    # `name=` is a Langfuse-only kwarg the wrapper strips before forwarding to the real API.
    from langfuse.openai import OpenAI

    checklist = "\n".join(f"- {q}" for q in template_queries) or "(empty — no checklist queries yet)"
    client = OpenAI(max_retries=10)
    return client.responses.parse(
        model=config.LLM_MODEL,
        temperature=0,
        input=[
            {"role": "system", "content": LLM_GAP_SUBQUERIES_SYSTEM},
            {
                "role": "user",
                "content": f"Patient state: {st.model_dump_json()}\nDerived: {derive(st)}\nNote: {note}\n\n"
                f"Checklist queries already covered:\n{checklist}",
            },
        ],
        text_format=SubQueries,
        name="llm_gap_subqueries",
    )


def build_llm_gap_subqueries(st: PatientState, note: str, template_queries: list[str]) -> list[str]:
    """The queries `build_template_subqueries` doesn't have a rule for — the LLM sees the
    checklist and is asked to fill gaps only, not regenerate it independently. Combine with the
    template by plain concatenation (`template_queries + build_llm_gap_subqueries(...)`); no
    string-matching dedup needed since the model is instructed not to repeat the checklist."""
    return _call_llm_for_subqueries(st, note, template_queries).output_parsed.queries


def interleave(per_query_rankings: list[list[tuple[str, float]]], limit: int) -> list[tuple[str, float]]:
    # round-robin across sub-queries so every care domain gets represented
    out, seen = [], set()
    for rank in range(max((len(r) for r in per_query_rankings), default=0)):
        for ranking in per_query_rankings:
            if rank < len(ranking) and ranking[rank][0] not in seen:
                seen.add(ranking[rank][0])
                out.append(ranking[rank])
    return out[:limit]


class RetrievalIndex:
    """BM25 + dense index over a KnowledgeBase, plus the retrieval strategies and LLM screening.

    Building this loads the local embedding model and (lazily, per reranker) the cross-encoders —
    expensive, so callers should build one instance and reuse it (Streamlit: st.cache_resource).
    """

    def __init__(self, kb: KnowledgeBase):
        from rank_bm25 import BM25Okapi

        self.kb = kb
        self.corpus_ids = kb.corpus_ids
        self.stmt_by_id = kb.stmt_by_id
        self.corpus_texts = [index_text(s) for s in kb.statements]
        self._id_index = {sid: i for i, sid in enumerate(self.corpus_ids)}

        self.bm25 = BM25Okapi([tokenize(t) for t in self.corpus_texts])
        self._embedder = None
        self.doc_vectors = self._embed_docs(self.corpus_texts)
        self._rerankers: dict[str, object] = {}

    # -- embeddings -----------------------------------------------------
    def _get_embedder(self):
        if self._embedder is None:
            from sentence_transformers import SentenceTransformer

            self._embedder = SentenceTransformer(config.LOCAL_EMBEDDING_MODEL)
        return self._embedder

    def _embed_docs(self, texts: list[str]) -> np.ndarray:
        if config.EMBEDDING_BACKEND == "local":
            return self._get_embedder().encode(texts, normalize_embeddings=True, batch_size=32)
        from openai import OpenAI

        resp = OpenAI(max_retries=10).embeddings.create(model=config.OPENAI_EMBEDDING_MODEL, input=texts)
        v = np.array([d.embedding for d in resp.data])
        return v / np.linalg.norm(v, axis=1, keepdims=True)

    def _embed_query(self, text: str) -> np.ndarray:
        if config.EMBEDDING_BACKEND == "local":
            prefix = "Represent this sentence for searching relevant passages: "
            return self._get_embedder().encode([prefix + text], normalize_embeddings=True)[0]
        return self._embed_docs([text])[0]

    # -- ranking ----------------------------------------------------------
    def rank_dense(self, query: str, candidate_ids: list[str]) -> list[tuple[str, float]]:
        q = self._embed_query(query)
        idx = [self._id_index[c] for c in candidate_ids]
        scores = self.doc_vectors[idx] @ q
        order = np.argsort(-scores)
        return [(candidate_ids[i], float(scores[i])) for i in order]

    def rank_bm25(self, query: str, candidate_ids: list[str]) -> list[tuple[str, float]]:
        scores = self.bm25.get_scores(tokenize(query))
        pairs = [(c, float(scores[self._id_index[c]])) for c in candidate_ids]
        return sorted(pairs, key=lambda x: -x[1])

    @staticmethod
    def _rrf(rankings: list[list[tuple[str, float]]], k: int = 60) -> list[tuple[str, float]]:
        fused: dict[str, float] = defaultdict(float)
        for ranking in rankings:
            for rank, (doc_id, _) in enumerate(ranking):
                fused[doc_id] += 1.0 / (k + rank + 1)
        return sorted(fused.items(), key=lambda x: -x[1])

    def hybrid(self, query: str, candidate_ids: list[str]) -> list[tuple[str, float]]:
        return self._rrf([self.rank_dense(query, candidate_ids), self.rank_bm25(query, candidate_ids)])

    def _get_reranker(self, name: str):
        if name not in self._rerankers:
            from sentence_transformers import CrossEncoder

            self._rerankers[name] = CrossEncoder(config.RERANKERS[name])
        return self._rerankers[name]

    def rerank(self, query: str, doc_ids: list[str], reranker_name: str) -> list[tuple[str, float]]:
        ce = self._get_reranker(reranker_name)
        scores = ce.predict([(query, index_text(self.stmt_by_id[i])) for i in doc_ids])
        return sorted(zip(doc_ids, map(float, scores)), key=lambda x: -x[1])

    # -- LLM-based retrieval (no sub-queries, no embeddings/BM25 — the LLM reads everything) ---
    @observe(name="llm_based_retrieval", as_type="retriever")
    def llm_based_retrieval(self, st: PatientState, note: str, eligibility_labels: dict | None = None) -> list[str]:
        """After filtering, give the LLM every remaining statement (~8k tokens) and let it pick
        directly. No template or LLM sub-queries are built on this path at all — compare with
        `build_template_subqueries`/`build_llm_gap_subqueries`, used by the query-reformulation
        strategies below instead."""
        from langfuse.openai import OpenAI

        eligibility_labels = (
            eligibility_labels if eligibility_labels is not None else label_statement_eligibility(self.kb, st)
        )
        listing = "\n".join(
            f"[{sid}] ({self.stmt_by_id[sid]['domain']}) {self.stmt_by_id[sid]['text']}"
            + (f"  <needs: {', '.join(eligibility_labels[sid][2])}>" if eligibility_labels[sid][2] else "")
            for sid in self.corpus_ids
            if eligibility_labels[sid][0] != "excluded"
        )
        prompt = f"PATIENT\n{st.model_dump_json()}\nDerived: {derive(st)}\nNote: {note}\n\nSTATEMENTS\n{listing}"

        resp = OpenAI(max_retries=10).responses.parse(
            model=config.LLM_MODEL,
            temperature=0,
            input=[
                {
                    "role": "system",
                    "content": "Select the guideline statements a clinician should review for this visit, "
                    "most important first (at most 25). Return only statement_ids from the list.",
                },
                {"role": "user", "content": prompt},
            ],
            text_format=Screening,
            name="llm_based_retrieval.generate",
        )
        picked = resp.output_parsed.relevant
        return [sid for sid in picked if sid in self.stmt_by_id]

    # -- top-level dispatcher ------------------------------------------------
    @observe(name="retrieve", as_type="retriever")
    def retrieve(
        self,
        st: PatientState,
        note: str,
        strategy: str,
        k: int = 15,
        reranker_name: str = config.DEFAULT_RERANKER,
        per_query: int = 8,
        subqueries: list[str] | None = None,
        eligibility_labels: dict | None = None,
    ) -> list[tuple[str, float]]:
        """The one traced entry point. `llm_based_retrieval_plus_query_reformulation` internally
        combines the `llm_based_retrieval` and `code_and_llm_query_reformulation_rerank`
        strategies, but does so via `_retrieve` (not a recursive call back into this method) so a
        single request produces one "retrieve" span and computes the eligibility labels once, not
        once per internal strategy branch.

        Pass `eligibility_labels` (from `label_statement_eligibility`) if the caller already
        computed it, to avoid a second, redundant computation."""
        eligibility_labels = (
            eligibility_labels if eligibility_labels is not None else label_statement_eligibility(self.kb, st)
        )
        return self._retrieve(st, note, strategy, eligibility_labels, k, reranker_name, per_query, subqueries)

    def _retrieve(
        self,
        st: PatientState,
        note: str,
        strategy: str,
        eligibility_labels: dict,
        k: int = 15,
        reranker_name: str = config.DEFAULT_RERANKER,
        per_query: int = 8,
        subqueries: list[str] | None = None,
    ) -> list[tuple[str, float]]:
        allowed = [sid for sid in self.corpus_ids if eligibility_labels[sid][0] != "excluded"]

        if strategy == "llm_based_retrieval":
            picked = self.llm_based_retrieval(st, note, eligibility_labels=eligibility_labels)
            return [(sid, 0.0) for sid in picked][:k]
        if strategy == "llm_based_retrieval_plus_query_reformulation":
            # LLM picks first (precise, ordered); remaining slots filled from combined retrieval,
            # which catches routine care the LLM skips. Both lists come from the same filtered candidates.
            picked = self._retrieve(st, note, "llm_based_retrieval", eligibility_labels, k=k)
            seen = {sid for sid, _ in picked}
            fill = [
                (sid, sc)
                for sid, sc in self._retrieve(
                    st,
                    note,
                    "code_and_llm_query_reformulation_rerank",
                    eligibility_labels,
                    k=k,
                    reranker_name=reranker_name,
                )
                if sid not in seen
            ]
            return (picked + fill)[:k]
        if strategy in ("llm_query_reformulation_rerank", "code_and_llm_query_reformulation_rerank"):
            # code checklist first (routine care is always asked); the LLM sees it and fills gaps
            # only — no post-hoc string-matching merge needed, just concatenate.
            template_queries = (
                build_template_subqueries(st) if strategy == "code_and_llm_query_reformulation_rerank" else []
            )
            gap_queries = build_llm_gap_subqueries(st, note, template_queries)
            subqueries = template_queries + gap_queries
            strategy = "code_query_reformulation_rerank"

        queries = subqueries or build_template_subqueries(st)
        candidates = [self.hybrid(q, allowed)[: per_query * 2] for q in queries]
        if strategy == "code_query_reformulation":
            return interleave([r[:per_query] for r in candidates], k)
        if strategy == "code_query_reformulation_rerank":
            reranked = [
                self.rerank(q, [i for i, _ in r], reranker_name)[:per_query] for q, r in zip(queries, candidates)
            ]
            return interleave(reranked, k)
        if strategy == "filtered_hybrid_raw":
            return self.hybrid(note, allowed)[:k]
        if strategy == "dense_raw":
            return self.rank_dense(note, self.corpus_ids)[:k]
        if strategy == "hybrid_raw":
            return self.hybrid(note, self.corpus_ids)[:k]
        raise ValueError(strategy)
